def _rows(path):
    if path.suffix.lower() in (".xlsx", ".xls"):
        for row in pd.read_excel(path, header=None, dtype=str).fillna("").values.tolist():
            yield [str(x).strip() for x in row]
    else:
        with path.open(encoding="utf-8", errors="ignore") as f:
            for line in f:
                yield [x.strip().strip('"') for x in re.split(r"\t|,", line.rstrip("\n"))]


def _files(word):
    return sorted(p for p in REF_DIR.iterdir() if word in p.name.lower() and p.suffix.lower() in (".txt", ".csv", ".xlsx", ".xls")) \
        if REF_DIR.exists() else []


def _load_ptp():
    """Rows that start with two procedure codes. Skips deleted edits and indicator 9 (not applicable)."""
    today = dt.date.today().strftime("%Y%m%d")
    out = {}
    for path in _files("ptp"):
        for cells in _rows(path):
            if len(cells) < 2 or not (CODE.match(cells[0]) and CODE.match(cells[1])):
                continue
            ind = next((int(x) for x in cells[2:] if x in ("0", "1", "9")), None)
            dates = [x for x in cells[2:] if re.fullmatch(r"\d{8}", x)]
            if ind == 9 or (len(dates) >= 2 and dates[1] < today):
                continue
            out[(cells[0], cells[1])] = ind
    return out


def _load_mue():
    out = {}
    for path in _files("mue"):
        for cells in _rows(path):
            if len(cells) >= 2 and CODE.match(cells[0]) and cells[1].isdigit():
                out[cells[0]] = int(cells[1])
    return out


